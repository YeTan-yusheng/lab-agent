from enum import IntEnum, StrEnum


class ReservationStatus(IntEnum):
    PENDING = 0
    APPROVED = 1
    REJECTED = 2
    CANCELLED = 3
    EXPIRED = 4


class ReservationAction(StrEnum):
    SUBMIT = "submit"
    APPROVE = "approve"
    REJECT = "reject"
    CANCEL = "cancel"
    FORCE_CANCEL = "force_cancel"
    EXPIRE = "expire"


class ReservationErrorCode(StrEnum):
    NOT_FOUND = "RESERVATION_NOT_FOUND"
    FORBIDDEN = "RESERVATION_FORBIDDEN"
    SELF_AUDIT_REQUIRED = "SELF_AUDIT_REQUIRED"
    SELF_AUDIT_INVALID = "SELF_AUDIT_INVALID"
    INVALID_STATUS_TRANSITION = "INVALID_STATUS_TRANSITION"
    CANCEL_TOO_LATE = "CANCEL_TOO_LATE"
    REJECT_REASON_REQUIRED = "REJECT_REASON_REQUIRED"
    REJECT_REASON_NOT_ALLOWED = "REJECT_REASON_NOT_ALLOWED"
    CANCEL_REASON_REQUIRED = "CANCEL_REASON_REQUIRED"
    INVALID_AUDIT_STATUS = "INVALID_AUDIT_STATUS"
    CONFLICT = "RESERVATION_CONFLICT"
    INTERNAL_ERROR = "INTERNAL_ERROR"
